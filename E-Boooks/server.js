/* ==========================================
   17. UNLOCK YEAR COLLECTION
========================================== */

// Note: This in-memory limiter is best-effort only.
// For production-wide rate limiting on Vercel,
// use a shared Redis or database-backed limiter.

const failedAttempts = new Map();

const MAX_ATTEMPTS = 5;
const LOCK_DURATION = 15 * 60 * 1000;

app.post(
    "/api/books/unlock",
    requireApiLogin,
    async (req, res) => {

        try {

            const {
                year,
                bookId,
                passkey
            } = req.body || {};

            let selectedYear = Number(year);

            const selectedBookId = Number(bookId);

            if (
                !isValidYear(selectedYear) &&
                isValidBookId(selectedBookId)
            ) {
                selectedYear = getYearFromBookId(
                    selectedBookId
                );
            }

            if (
                !isValidYear(selectedYear) ||
                typeof passkey !== "string" ||
                !/^\d{4}$/.test(passkey)
            ) {
                return res.status(400).json({
                    success: false,
                    message: "Enter a valid 4-digit year-level passkey."
                });
            }

            if (
                bookId !== null &&
                bookId !== undefined &&
                (
                    !isValidBookId(selectedBookId) ||
                    getYearFromBookId(selectedBookId) !==
                        selectedYear
                )
            ) {
                return res.status(400).json({
                    success: false,
                    message: "The selected book does not belong to this year level."
                });
            }

            const collection =
                YEAR_LEVELS[selectedYear];

            if (
                getUnlockedYears(req).includes(
                    selectedYear
                )
            ) {
                return res.json({
                    success: true,
                    message: "Collection already unlocked.",
                    year: selectedYear,
                    unlockedYears: getUnlockedYears(req)
                });
            }

            const attemptKey =
                `${req.session.user.id}:${selectedYear}:${req.ip}`;

            const now = Date.now();

            let attempts = failedAttempts.get(
                attemptKey
            ) || {
                count: 0,
                blockedUntil: 0
            };

            if (attempts.blockedUntil > now) {

                const remaining = Math.ceil(
                    (attempts.blockedUntil - now) / 60000
                );

                return res.status(429).json({
                    success: false,
                    message: `Too many attempts. Try again in ${remaining} minute(s).`
                });
            }

            if (
                attempts.blockedUntil &&
                attempts.blockedUntil <= now
            ) {
                attempts = {
                    count: 0,
                    blockedUntil: 0
                };
            }

            if (!secureCompare(
                passkey,
                collection.passkey
            )) {

                attempts.count++;

                if (attempts.count >= MAX_ATTEMPTS) {
                    attempts.blockedUntil =
                        now + LOCK_DURATION;
                }

                failedAttempts.set(
                    attemptKey,
                    attempts
                );

                return res.status(403).json({
                    success: false,
                    message: attempts.blockedUntil
                        ? "Too many incorrect attempts. Try again in 15 minutes."
                        : "Incorrect year-level passkey."
                });
            }

            failedAttempts.delete(attemptKey);

            // Only one year level may be unlocked at a time.
            req.session.activeYear = selectedYear;

            // Clear the old multi-year access state.
            delete req.session.unlockedYears;

            await saveSession(req);

            return res.json({
                success: true,
                message:
                    `${collection.name} unlocked successfully!`,
                year: selectedYear,
                unlockedYears: getUnlockedYears(req)
            });

        } catch (error) {

            console.error(
                "Collection unlock error:",
                error
            );

            return res.status(500).json({
                success: false,
                message: "Unable to unlock collection."
            });
        }
    }
);

