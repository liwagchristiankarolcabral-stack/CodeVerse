app.post("/api/register", async (req, res) => {

    try {

        const {
            fullName,
            email,
            password
        } = req.body || {};

        if (!fullName || !email || !password) {
            return res.status(400).json({
                success: false,
                message: "Please complete all fields."
            });
        }

        const name = String(fullName).trim();
        const userEmail = String(email)
            .trim()
            .toLowerCase();

        const userPassword = String(password);

        if (
            name.length < 2 ||
            name.length > 80
        ) {
            return res.status(400).json({
                success: false,
                message: "Full name must be between 2 and 80 characters."
            });
        }

        if (
            !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(userEmail) ||
            userEmail.length > 254
        ) {
            return res.status(400).json({
                success: false,
                message: "Enter a valid email address."
            });
        }

        if (
            userPassword.length < 10 ||
            Buffer.byteLength(userPassword, "utf8") > 72
        ) {
            return res.status(400).json({
                success: false,
                message: "Password must be at least 10 characters and no more than 72 bytes."
            });
        }

        const existing = await pool.query(
            "SELECT id FROM users WHERE email = $1",
            [userEmail]
        );

        if (existing.rows.length > 0) {
            return res.status(409).json({
                success: false,
                message: "This email is already registered."
            });
        }

        const hash = await bcrypt.hash(
            userPassword,
            12
        );

        let result;

        try {

            result = await pool.query(`
                INSERT INTO users (
                    full_name,
                    email,
                    password_hash
                )
                VALUES ($1, $2, $3)
                RETURNING id
            `, [
                name,
                userEmail,
                hash
            ]);

        } catch (error) {

            if (error.code === "23505") {
                return res.status(409).json({
                    success: false,
                    message: "This email is already registered."
                });
            }

            throw error;
        }

        await regenerateSession(req);

        req.session.user = {
            id: result.rows[0].id,
            fullName: name,
            email: userEmail
        };

        await saveSession(req);

        return res.status(201).json({
            success: true,
            message: "Welcome to CodeVerse! Account created successfully.",
            user: req.session.user
        });

    } catch (error) {

        console.error(
            "Registration error:",
            error
        );

        return res.status(500).json({
            success: false,
            message: "Unable to complete registration."
        });
    }
});

