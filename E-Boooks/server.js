function loadManifest(filePath) {

    if (!fs.existsSync(filePath)) {
        console.warn(
            "Manifest not found:",
            path.basename(filePath)
        );
        return {};
    }

    try {

        const manifest = JSON.parse(
            fs.readFileSync(filePath, "utf8")
        );

        if (
            !manifest ||
            typeof manifest !== "object" ||
            Array.isArray(manifest)
        ) {
            throw new Error(
                "Manifest must be a JSON object."
            );
        }

        return manifest;

    } catch (error) {

        console.error(
            "Manifest error:",
            error.message
        );

        return {};
    }
}

const bookManifest = loadManifest(
    BOOK_MANIFEST_FILE
);

const coverManifest = loadManifest(
    COVER_MANIFEST_FILE
);

/* ==========================================
   11. PROTECTED FILE RESOLUTION
========================================== */

function getProtectedHtmlFile(manifest, bookId) {

    if (!isValidBookId(bookId)) {
        return null;
    }

    const filename = manifest[String(bookId)];

    if (
        typeof filename !== "string" ||
        !filename.trim()
    ) {
        return null;
    }

    const absolutePath = path.resolve(
        PROTECTED_FOLDER,
        filename
    );

    const relativePath = path.relative(
        PROTECTED_FOLDER,
        absolutePath
    );

    if (
        !relativePath ||
        relativePath === ".." ||
        relativePath.startsWith(".." + path.sep) ||
        path.isAbsolute(relativePath)
    ) {
        return null;
    }

    if (
        path.extname(absolutePath).toLowerCase()
        !== ".html"
    ) {
        return null;
    }

    try {

        const root = fs.realpathSync(
            PROTECTED_FOLDER
        );

        const file = fs.realpathSync(
            absolutePath
        );

        const realRelative = path.relative(
            root,
            file
        );

        if (
            !realRelative ||
            realRelative === ".." ||
            realRelative.startsWith(".." + path.sep) ||
            path.isAbsolute(realRelative)
        ) {
            return null;
        }

        if (!fs.statSync(file).isFile()) {
            return null;
        }

        return file;

    } catch {
        return null;
    }
}

function getProtectedBookFile(bookId) {
    return getProtectedHtmlFile(
        bookManifest,
        bookId
    );
}

function getProtectedCoverFile(bookId) {
    return getProtectedHtmlFile(
        coverManifest,
        bookId
    );
}

