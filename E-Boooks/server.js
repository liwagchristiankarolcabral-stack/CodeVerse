const MAX_BOOK_ID = 30;

/* ==========================================
   9. BOOK ACCESS HELPERS
========================================== */

function isValidBookId(bookId) {
    return Number.isInteger(bookId) &&
        bookId >= 1 &&
        bookId <= MAX_BOOK_ID;
}

function isValidYear(year) {
    return Number.isInteger(year) &&
        Object.prototype.hasOwnProperty.call(
            YEAR_LEVELS,
            year
        );
}

function getYearFromBookId(bookId) {

    if (!isValidBookId(bookId)) {
        return null;
    }

    for (const [year, collection] of
        Object.entries(YEAR_LEVELS)) {

        if (collection.bookIds.includes(bookId)) {
            return Number(year);
        }
    }

    return null;
}

function getUnlockedYears(req) {
    const activeYear = Number(req.session?.activeYear);

    return isValidYear(activeYear)
        ? [activeYear]
        : [];
}

function hasYearAccess(req, bookId) {

    const year = getYearFromBookId(bookId);

    return Boolean(
        year && getUnlockedYears(req).includes(year)
    );
}

function secureCompare(first, second) {

    if (
        typeof first !== "string" ||
        typeof second !== "string"
    ) {
        return false;
    }

    const firstHash = crypto
        .createHash("sha256")
        .update(first)
        .digest();

    const secondHash = crypto
        .createHash("sha256")
        .update(second)
        .digest();

    return crypto.timingSafeEqual(
        firstHash,
        secondHash
    );
}

